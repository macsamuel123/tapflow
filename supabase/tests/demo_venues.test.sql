-- Testers' own venues: the public key can read menus but never write, and never reads tokens or
-- key hashes. Needs supabase/demo/*.sql, which `make seed` loads. Everything is rolled back.
begin;
create extension if not exists pgtap with schema extensions;
set search_path = public, extensions;

select plan(34);

create function pg_temp.new_venue(ip text, slug text default 'harbour-taproom') returns demo.venues language sql as $$
  select demo.create_venue(ip, 5,
    jsonb_build_object('slug', slug, 'name', 'Harbour Taproom', 'industry', 'breweries', 'country', 'CA',
                       'region', 'British Columbia', 'currency', 'CAD'),
    '[{"id":"t1","label":"Table 1","service_mode":"delivery","spot_number":1,"active":true},
      {"id":"p1","label":"Bar","service_mode":"pickup","spot_number":null,"active":true}]'::jsonb,
    '[]'::jsonb, false, gen_random_uuid()::text);
$$;

-- A clean slate, whatever other tests left behind. Rolled back at the end.
delete from demo.orders;
delete from demo.item_stock;
delete from demo.venues;
delete from demo.rate_limits;

select is((pg_temp.new_venue('ip-a')).slug, 'harbour-taproom', 'a venue keeps its slug');
select is((pg_temp.new_venue('ip-a')).slug, 'harbour-taproom-2', 'a taken slug gets a number');
select is((pg_temp.new_venue('ip-a', 'demo-brewery')).slug, 'demo-brewery-2', 'demo slugs are reserved');
select is((select count(*)::int from demo.touchpoints t join demo.venues v on v.id = t.venue_id where v.slug = 'harbour-taproom'), 2, 'touchpoints are saved');
select is((select count(distinct token)::int from demo.touchpoint_secrets s join demo.venues v on v.id = s.venue_id where v.slug = 'harbour-taproom'), 2, 'each touchpoint gets its own token');
select ok((select bool_and(length(token) = 32) from demo.touchpoint_secrets), 'tokens are generated by the database');

-- ------------------------------------------------------------------ the daily limit
select lives_ok($$ select pg_temp.new_venue('ip-b', 'b1'); select pg_temp.new_venue('ip-b', 'b2'); select pg_temp.new_venue('ip-b', 'b3'); select pg_temp.new_venue('ip-b', 'b4'); select pg_temp.new_venue('ip-b', 'b5') $$, 'five venues a day from one IP');
select throws_ok($$ select pg_temp.new_venue('ip-b', 'b6') $$, 'P0001', 'rate_limited', 'the sixth is refused');
select lives_ok($$ select pg_temp.new_venue('ip-c', 'c1') $$, 'another IP is unaffected');

-- ------------------------------------------------------------------ saving
create temp table v on commit drop as select * from demo.venues where slug = 'harbour-taproom';
grant select on v to anon;
select is((select (demo.update_venue((select id from v), 1, '{"name":"New name"}', null, null, null)).menu_version), 2, 'a save bumps the version');
select throws_ok($$ select demo.update_venue((select id from v), 1, '{"name":"Stale"}', null, null, null) $$,
  'P0001', 'version_conflict', 'a stale save is refused');
select is((select name from demo.venues where id = (select id from v)), 'New name', 'the stale save changed nothing');

create temp table before_tokens on commit drop as
  select touchpoint_id, token from demo.touchpoint_secrets where venue_id = (select id from v);
select demo.update_venue((select id from v), 2, null, null, null,
  '[{"id":"t1","label":"Table 1","service_mode":"delivery","spot_number":1,"active":true,"token":"keep"},
    {"id":"t2","label":"Table 2","service_mode":"delivery","spot_number":2,"active":true},
    {"id":"p1","label":"Bar","service_mode":"pickup","active":true,"token":"regenerate"}]'::jsonb);
select is((select token from demo.touchpoint_secrets where venue_id = (select id from v) and touchpoint_id = 't1'),
  (select token from before_tokens where touchpoint_id = 't1'), 'an unchanged touchpoint keeps its token');
select isnt((select token from demo.touchpoint_secrets where venue_id = (select id from v) and touchpoint_id = 'p1'),
  (select token from before_tokens where touchpoint_id = 'p1'), 'regenerate issues a new token');
select ok((select token <> 'keep' from demo.touchpoint_secrets where venue_id = (select id from v) and touchpoint_id = 't1'),
  'a client cannot choose its own token');
select is((select count(*)::int from demo.touchpoints where venue_id = (select id from v)), 3, 'new touchpoints are added');

-- ------------------------------------------------------------------ fixed demos stay separate
select demo.create_order('ip-z', 10, jsonb_build_object('venue_slug', 'harbour-taproom', 'touchpoint_id', 't1',
  'touchpoint_label', 'Table 1', 'service_mode', 'delivery', 'items', '[]'::jsonb, 'subtotal_cents', 100,
  'tax_lines', '[]'::jsonb, 'tax_cents', 5, 'total_cents', 105));
select demo.create_order('ip-z', 10, jsonb_build_object('venue_slug', 'demo-brewery', 'touchpoint_id', 't1',
  'touchpoint_label', 'Table 1', 'service_mode', 'delivery', 'items', '[]'::jsonb, 'subtotal_cents', 100,
  'tax_lines', '[]'::jsonb, 'tax_cents', 5, 'total_cents', 105));
select demo.clear_all();
select is((select count(*)::int from demo.orders where venue_slug = 'harbour-taproom'), 1, 'Clear leaves own venues alone');
select is((select count(*)::int from demo.orders where venue_slug = 'demo-brewery'), 0, 'Clear still clears the demo venues');
update demo.orders set created_at = now() - interval '3 days';
select demo.cleanup_old();
select is((select count(*)::int from demo.orders where venue_slug = 'harbour-taproom'), 1, '24-hour cleanup leaves own venues alone');

-- ------------------------------------------------------------------ 14-day expiry
update demo.venues set last_activity_at = now() - interval '15 days' where slug = 'harbour-taproom';
update demo.venues set last_activity_at = now() - interval '13 days' where slug = 'harbour-taproom-2';
select is((select array_agg(slug) from demo.expired_venues(10)), array['harbour-taproom'], 'only venues idle for 14 days expire');
select demo.delete_venue('harbour-taproom');
select is((select count(*)::int from demo.venues where slug = 'harbour-taproom'), 0, 'delete removes the venue');
select is((select count(*)::int from demo.orders where venue_slug = 'harbour-taproom'), 0, 'delete removes its orders');
select is((select count(*)::int from demo.touchpoints where venue_id = (select id from v)), 0, 'delete removes its touchpoints');
select is((select count(*)::int from demo.touchpoint_secrets where venue_id = (select id from v)), 0, 'delete removes its tokens');

-- ------------------------------------------------------------------ as anon
set local role anon;
select ok((select count(*) from demo.venues) >= 1, 'anon can read venues');
select lives_ok($$ select label from demo.touchpoints $$, 'anon can read touchpoints');
select lives_ok($$ select menu from demo.venue_menus $$, 'anon can read menus');
select throws_ok($$ select token from demo.touchpoint_secrets $$, '42501', null, 'anon cannot read QR tokens');
select throws_ok($$ select key_hash from demo.venue_keys $$, '42501', null, 'anon cannot read key hashes');
select throws_ok($$ select token from demo.touchpoints $$, '42703', null, 'tokens are not on touchpoints');
select throws_ok($$ insert into demo.venues (slug, name, industry, country, region, currency) values ('x1', 'X', 'x', 'CA', 'BC', 'CAD') $$, '42501', null, 'anon cannot create venues');
select throws_ok($$ update demo.venues set name = 'Hacked' $$, '42501', null, 'anon cannot change venues');
select throws_ok($$ delete from demo.venue_menus $$, '42501', null, 'anon cannot change menus');
select throws_ok($$ select demo.delete_venue('harbour-taproom-2') $$, '42501', null, 'anon cannot call the venue functions');

select * from finish();
rollback;
